/**
 * Base de datos centralizada de modelos de iPhone.
 *
 * Una sola fuente de verdad: el catálogo, las fichas, el comparador, la galería,
 * el carrito y el panel administrativo leen de aquí. Lo que cambia con el
 * negocio (precios, inventario, condición, fotos) NO vive aquí: está en
 * `public/data/store.json` y se combina en `services/catalogService.js`.
 *
 * Reglas de este archivo:
 *  - Solo especificaciones publicadas por Apple. Fuente principal de consulta:
 *    https://www.apple.com/co/iphone/compare/ (incluye todos los modelos desde
 *    iPhone 7) y las páginas de especificaciones de cada modelo vigente.
 *  - `verification.level`:
 *      'apple-specs'   → copiado de la página de especificaciones oficial indicada en `source`.
 *      'apple-compare' → datos del comparador oficial de Apple Colombia; conviene revisarlos
 *                        contra la ficha técnica de soporte de Apple antes de publicar precios.
 *  - `hex` de cada color es una APROXIMACIÓN visual para las muestras y el modelo 3D;
 *    el nombre del color es el oficial.
 *  - `appleStatus`: 'vigente' = Apple Colombia lo vende hoy (revisado el 2026-11-02);
 *    'descontinuado' = Apple ya no lo vende nuevo. Esto es independiente del
 *    inventario de BUNEMA (nuevo / usado / reacondicionado).
 *  - `design` describe la forma general para la ilustración y el modelo 3D
 *    generados por código. No son fotografías ni renders oficiales.
 */

